(function () {
  let lang = 'fr';
  try { lang = localStorage.getItem('lang') || ''; } catch {}
  if (lang !== 'fr' && lang !== 'en') lang = (navigator.language || 'fr').toLowerCase().startsWith('fr') ? 'fr' : 'en';
  window.LANG = lang;
})();

// t('Texte {x}', { x: 1 }) → texte traduit avec ses valeurs
window.t = function (fr, vars) {
  let s = window.LANG === 'en' && window.EN[fr] != null ? window.EN[fr] : fr;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
};

// Traduit les textes fixes de la page (et se souvient du français d'origine)
const ORIG = new WeakMap();
window.applyStaticLang = function () {
  document.documentElement.lang = window.LANG;
  const walk = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walk.nextNode()) nodes.push(walk.currentNode);
  for (const n of nodes) {
    if (n.parentElement.closest('#cards,#jobs,#log,#onkey,#drive-meta,#drive-sel,script,style')) continue;
    if (!ORIG.has(n)) ORIG.set(n, n.nodeValue);
    const src = ORIG.get(n), key = src.trim();
    if (key && window.EN[key] != null) n.nodeValue = src.replace(key, window.t(key));
  }
  document.querySelectorAll('[placeholder],[aria-label]').forEach((el) => {
    for (const a of ['placeholder', 'aria-label']) {
      if (!el.hasAttribute(a)) continue;
      const k = 'data-fr-' + a;
      if (!el.hasAttribute(k)) el.setAttribute(k, el.getAttribute(a));
      el.setAttribute(a, window.t(el.getAttribute(k)));
    }
  });
  document.querySelectorAll('.lang-btn').forEach((b) => b.classList.toggle('on', b.dataset.lang === window.LANG));
};
